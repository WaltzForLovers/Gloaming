func joinGenres(genres []string) string {
	out := make([]string, 0, len(genres))
	seen := map[string]bool{}
	for _, genre := range genres {
		genre = strings.TrimSpace(genre)
		if genre == "" || strings.Contains(genre, ",") || seen[genre] {
			continue
		}
		seen[genre] = true
		out = append(out, genre)
	}
	return strings.Join(out, ",")
}

func splitGenres(raw string) []string {
	if raw == "" {
		return nil
	}
	return strings.Split(raw, ",")
}

func (db *DB) ensureEpisodes(ctx context.Context, title Title) error {
	var count int
	if err := db.sql.QueryRowContext(ctx, `SELECT COUNT(*) FROM seasons WHERE title_id = $1`, title.ID).Scan(&count); err != nil {
		return err
	}
	if count > 0 {
		return nil
	}
	n := title.EpisodeCount
	if n < 1 {
		n = 1
	}
	seeds := make([]EpisodeSeed, n)
	for i := range seeds {
		seeds[i] = EpisodeSeed{SeasonNumber: 1, Number: i + 1, Runtime: title.AverageMinutes}
	}
	return db.ReplaceEpisodes(ctx, title.ID, seeds)
}

func (db *DB) ReplaceEpisodes(ctx context.Context, titleID int64, seeds []EpisodeSeed) error {
	if len(seeds) == 0 {
		return nil
	}
	tx, err := db.sql.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()

	kept := make([]int64, 0, len(seeds))
	seasons := map[int]int64{}
	for _, seed := range seeds {
		seasonNumber := seed.SeasonNumber
		if seasonNumber < 1 {
			seasonNumber = 1
		}
		number := seed.Number
		if number < 1 {
			number = 1
		}
		seasonID, ok := seasons[seasonNumber]
		if !ok {
			err = tx.QueryRowContext(ctx, `
INSERT INTO seasons (title_id, number, poster) VALUES ($1, $2, $3)
ON CONFLICT (title_id, number) DO UPDATE SET
    poster = CASE WHEN EXCLUDED.poster <> '' THEN EXCLUDED.poster ELSE seasons.poster END
RETURNING id`, titleID, seasonNumber, seed.Poster).Scan(&seasonID)
			if err != nil {
				return err
			}
			seasons[seasonNumber] = seasonID
		}
		var episodeID int64
		err = tx.QueryRowContext(ctx, `
INSERT INTO episodes (season_id, number, name, runtime_minutes)
VALUES ($1, $2, $3, $4)
ON CONFLICT (season_id, number) DO UPDATE SET
    name = EXCLUDED.name,
    runtime_minutes = EXCLUDED.runtime_minutes
RETURNING id`, seasonID, number, seed.Name, seed.Runtime).Scan(&episodeID)
		if err != nil {
			return err
		}
		kept = append(kept, episodeID)
	}
	if len(kept) > 0 {
		if _, err := tx.ExecContext(ctx, `
DELETE FROM episodes
WHERE season_id IN (SELECT id FROM seasons WHERE title_id = $1)
  AND NOT (id = ANY($2::bigint[]))`, titleID, kept); err != nil {
			return err
		}
	}
	if _, err := tx.ExecContext(ctx, `
DELETE FROM seasons s
WHERE s.title_id = $1
  AND NOT EXISTS (SELECT 1 FROM episodes e WHERE e.season_id = s.id)
  AND NOT EXISTS (SELECT 1 FROM queue_items q WHERE q.season_id = s.id)`, titleID); err != nil {
		return err
	}
	return tx.Commit()
}

func (db *DB) CreateManual(ctx context.Context, ownerID int64, title Title) (Title, error) {
	if ownerID <= 0 {
		return Title{}, fmt.Errorf("manual title needs an owner")
	}
	title.Source = "manual"
	title.Poster = ""
	title.OwnerID = ownerID
	var lastErr error
	for range 5 {
		externalID, err := randomExternalID()
		if err != nil {
			return Title{}, err
		}
		saved, err := db.insertManual(ctx, externalID, title)
		if err == nil {
			if err := db.ensureEpisodes(ctx, saved); err != nil {
				return Title{}, err
			}
			return saved, nil
		}
		if !isUnique(err) {
			return Title{}, err
		}
		lastErr = err
	}
	return Title{}, lastErr
}

