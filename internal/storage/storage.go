func (db *DB) queueRow(ctx context.Context, userID, itemID int64) (QueueRow, error) {
	var row QueueRow
	err := db.sql.QueryRowContext(ctx, `
SELECT q.id, q.position, s.id, s.number,
       t.id, t.external_id, t.source, t.name, t.year, t.episode_count, t.average_minutes, t.poster,
       (SELECT COUNT(*) FROM seasons s2 WHERE s2.title_id = t.id)
FROM queue_items q
JOIN seasons s ON s.id = q.season_id
JOIN titles t ON t.id = s.title_id
WHERE q.user_id = $1 AND q.id = $2`, userID, itemID).Scan(
		&row.ID, &row.Position, &row.SeasonID, &row.SeasonNumber,
		&row.Title.ID, &row.Title.ExternalID, &row.Title.Source, &row.Title.Name, &row.Title.Year, &row.Title.EpisodeCount, &row.Title.AverageMinutes, &row.Title.Poster,
		&row.SeasonCount)
	if errors.Is(err, sql.ErrNoRows) {
		return QueueRow{}, ErrNotFound
	}
	if err != nil {
		return QueueRow{}, err
	}
	episodes, err := db.sql.QueryContext(ctx, `
SELECT e.runtime_minutes,
       EXISTS(SELECT 1 FROM watched w WHERE w.episode_id = e.id AND w.user_id = $2)
FROM episodes e
WHERE e.season_id = $1
ORDER BY e.number`, row.SeasonID, userID)
	if err != nil {
		return QueueRow{}, err
	}
	defer episodes.Close()
	for episodes.Next() {
		var runtime int
		var watched bool
		if err := episodes.Scan(&runtime, &watched); err != nil {
			return QueueRow{}, err
		}
		row.TotalEpisodes++
		if watched {
			continue
		}
		if runtime <= 0 {
			runtime = row.Title.AverageMinutes
		}
		row.Remaining = append(row.Remaining, runtime)
	}
	if row.Remaining == nil {
		row.Remaining = []int{}
	}
	return row, episodes.Err()
}

