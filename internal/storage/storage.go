func (db *DB) ManualTitles(ctx context.Context, ownerID int64, query string) ([]Title, error) {
	rows, err := db.sql.QueryContext(ctx, `
SELECT id, external_id, source, name, year, episode_count, average_minutes, poster, owner_id
FROM titles
WHERE owner_id = $1 AND source = 'manual' AND name ILIKE $2 ESCAPE '\'
ORDER BY name
LIMIT 8`, ownerID, likeContains(query))
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var titles []Title
	for rows.Next() {
		var title Title
		if err := rows.Scan(&title.ID, &title.ExternalID, &title.Source, &title.Name, &title.Year, &title.EpisodeCount, &title.AverageMinutes, &title.Poster, &title.OwnerID); err != nil {
			return nil, err
		}
		titles = append(titles, title)
	}
	if titles == nil {
		titles = []Title{}
	}
	return titles, rows.Err()
}

func likeContains(query string) string {
	var b strings.Builder
	b.WriteByte('%')
	for _, r := range query {
		if r == '\\' || r == '%' || r == '_' {
			b.WriteByte('\\')
		}
		b.WriteRune(r)
	}
	b.WriteByte('%')
	return b.String()
}

func randomExternalID() (int, error) {
	var buf [4]byte
	if _, err := rand.Read(buf[:]); err != nil {
		return 0, err
	}
	n := (int(buf[0])&0x7f)<<24 | int(buf[1])<<16 | int(buf[2])<<8 | int(buf[3])
	if n == 0 {
		return 1, nil
	}
	return n, nil
}

