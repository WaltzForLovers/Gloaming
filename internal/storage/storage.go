func (db *DB) DSN() string { return db.dsn }

func Open(dsn string) (*DB, error) {
	dsn, err := ensureDatabase(dsn)
	if err != nil {
		return nil, err
	}
	sqlDB, err := sql.Open("pgx", dsn)
	if err != nil {
		return nil, fmt.Errorf("open db: %w", err)
	}
	sqlDB.SetMaxOpenConns(8)
	db := &DB{sql: sqlDB, dsn: dsn}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	if err := sqlDB.PingContext(ctx); err != nil {
		sqlDB.Close()
		return nil, fmt.Errorf("open db: %w", err)
	}
	if err := db.migrate(); err != nil {
		sqlDB.Close()
		return nil, fmt.Errorf("migrate db: %w", err)
	}
	return db, nil
}

func ensureDatabase(dsn string) (string, error) {
	parsed, err := url.Parse(dsn)
	if err != nil || parsed.Path == "" || parsed.Path == "/" {
		return dsn, nil
	}
	name := parsed.Path[1:]
	sqlDB, err := sql.Open("pgx", dsn)
	if err != nil {
		return "", fmt.Errorf("open db: %w", err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	err = sqlDB.PingContext(ctx)
	cancel()
	sqlDB.Close()
	if err == nil {
		return dsn, nil
	}
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) || pgErr.Code != "3D000" {
		return dsn, nil
	}
	admin := *parsed
	admin.Path = "/postgres"
	adminDB, err := sql.Open("pgx", admin.String())
	if err != nil {
		return "", err
	}
	defer adminDB.Close()
	if _, err := adminDB.ExecContext(context.Background(), `CREATE DATABASE `+quoteIdent(name)); err != nil && !isUnique(err) {
		return "", fmt.Errorf("create database: %w", err)
	}
	return dsn, nil
}

func quoteIdent(name string) string {
	return `"` + replaceAll(name, `"`, `""`) + `"`
}

func replaceAll(s, old, new string) string {
	out := ""
	for i := 0; i < len(s); {
		if len(s)-i >= len(old) && s[i:i+len(old)] == old {
			out += new
			i += len(old)
			continue
		}
		out += s[i : i+1]
		i++
	}
	return out
}

