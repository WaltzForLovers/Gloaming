func (db *DB) MoveQueueItem(ctx context.Context, userID, itemID int64, delta int) error {
	tx, err := db.sql.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()

	var position int
	err = tx.QueryRowContext(ctx, `SELECT position FROM queue_items WHERE id = $1 AND user_id = $2`, itemID, userID).Scan(&position)
	if errors.Is(err, sql.ErrNoRows) {
		return ErrNotFound
	}
	if err != nil {
		return err
	}
	neighborPos := position + delta
	if neighborPos < 1 {
		return nil
	}
	var neighborID int64
	err = tx.QueryRowContext(ctx, `SELECT id FROM queue_items WHERE user_id = $1 AND position = $2`, userID, neighborPos).Scan(&neighborID)
	if errors.Is(err, sql.ErrNoRows) {
		return nil
	}
	if err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE queue_items SET position = -1 WHERE id = $1`, itemID); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE queue_items SET position = $1 WHERE id = $2`, position, neighborID); err != nil {
		return err
	}
	if _, err := tx.ExecContext(ctx, `UPDATE queue_items SET position = $1 WHERE id = $2`, neighborPos, itemID); err != nil {
		return err
	}
	return tx.Commit()
}

