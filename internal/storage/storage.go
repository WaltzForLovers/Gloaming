func (db *DB) CreateUser(ctx context.Context, username, passwordHash, email string) (User, error) {
	var id int64
	err := db.sql.QueryRowContext(ctx, `
INSERT INTO users (username, password_hash, created_at, email)
VALUES ($1, $2, $3, $4)
RETURNING id`, username, passwordHash, time.Now().UTC(), email).Scan(&id)
	if err != nil {
		switch uniqueConstraint(err) {
		case "":
			return User{}, err
		case "users_email_unique":
			return User{}, ErrEmailTaken
		default:
			return User{}, ErrUsernameTaken
		}
	}
	return User{ID: id, Username: username, PasswordHash: passwordHash}, nil
}

