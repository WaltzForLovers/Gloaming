func (db *DB) AddSeason(ctx context.Context, userID, seasonID int64) (QueueRow, error) {
	tx, err := db.sql.BeginTx(ctx, nil)
	if err != nil {
		return QueueRow{}, err
	}
	defer tx.Rollback()

	var owner sql.NullInt64
	err = tx.QueryRowContext(ctx, `
SELECT t.owner_id
FROM seasons s
JOIN titles t ON t.id = s.title_id
WHERE s.id = $1`, seasonID).Scan(&owner)
	if errors.Is(err, sql.ErrNoRows) || (err == nil && owner.Valid && owner.Int64 != userID) {
		return QueueRow{}, ErrNotFound
	}
	if err != nil {
		return QueueRow{}, err
	}
	var position int
	if err := tx.QueryRowContext(ctx, `SELECT COALESCE(MAX(position), 0) + 1 FROM queue_items WHERE user_id = $1`, userID).Scan(&position); err != nil {
		return QueueRow{}, err
	}
	var id int64
	err = tx.QueryRowContext(ctx, `
INSERT INTO queue_items (user_id, season_id, position) VALUES ($1, $2, $3)
RETURNING id`, userID, seasonID, position).Scan(&id)
	if err != nil {
		if isUnique(err) {
			return QueueRow{}, ErrQueueDuplicate
		}
		return QueueRow{}, err
	}
	if err := tx.Commit(); err != nil {
		return QueueRow{}, err
	}
	return db.queueRow(ctx, userID, id)
}

func (db *DB) AddAllSeasons(ctx context.Context, userID, titleID int64) ([]QueueRow, error) {
	var owner sql.NullInt64
	err := db.sql.QueryRowContext(ctx, `SELECT owner_id FROM titles WHERE id = $1`, titleID).Scan(&owner)
	if errors.Is(err, sql.ErrNoRows) || (err == nil && owner.Valid && owner.Int64 != userID) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, err
	}
	ids, err := db.seasonIDs(ctx, titleID)
	if err != nil {
		return nil, err
	}
	if len(ids) == 0 {
		return nil, ErrNotFound
	}
	tx, err := db.sql.BeginTx(ctx, nil)
	if err != nil {
		return nil, err
	}
	defer tx.Rollback()
	var position int
	if err := tx.QueryRowContext(ctx, `SELECT COALESCE(MAX(position), 0) FROM queue_items WHERE user_id = $1`, userID).Scan(&position); err != nil {
		return nil, err
	}
	var itemIDs []int64
	for _, seasonID := range ids {
		var queued int
		if err := tx.QueryRowContext(ctx, `SELECT COUNT(*) FROM queue_items WHERE user_id = $1 AND season_id = $2`, userID, seasonID).Scan(&queued); err != nil {
			return nil, err
		}
		if queued > 0 {
			continue
		}
		position++
		var id int64
		if err := tx.QueryRowContext(ctx, `
INSERT INTO queue_items (user_id, season_id, position) VALUES ($1, $2, $3)
RETURNING id`, userID, seasonID, position).Scan(&id); err != nil {
			return nil, err
		}
		itemIDs = append(itemIDs, id)
	}
	if len(itemIDs) == 0 {
		return nil, ErrQueueDuplicate
	}
	if err := tx.Commit(); err != nil {
		return nil, err
	}
	rows := make([]QueueRow, 0, len(itemIDs))
	for _, id := range itemIDs {
		row, err := db.queueRow(ctx, userID, id)
		if err != nil {
			return nil, err
		}
		rows = append(rows, row)
	}
	return rows, nil
}

