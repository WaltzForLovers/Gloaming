func (db *DB) TitleSeasons(ctx context.Context, titleID, userID int64) ([]SeasonRow, error) {
	rows, err := db.sql.QueryContext(ctx, `
SELECT s.id, s.number, s.poster, e.id, e.number, e.name, e.runtime_minutes,
       EXISTS(SELECT 1 FROM watched w WHERE w.episode_id = e.id AND w.user_id = $2)
FROM seasons s
JOIN episodes e ON e.season_id = s.id
WHERE s.title_id = $1
ORDER BY s.number, e.number`, titleID, userID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var seasons []SeasonRow
	index := map[int64]int{}
	for rows.Next() {
		var seasonID int64
		var seasonNumber int
		var poster string
		var episode EpisodeRow
		if err := rows.Scan(&seasonID, &seasonNumber, &poster, &episode.ID, &episode.Number, &episode.Name, &episode.Runtime, &episode.Watched); err != nil {
			return nil, err
		}
		at, ok := index[seasonID]
		if !ok {
			seasons = append(seasons, SeasonRow{ID: seasonID, Number: seasonNumber, Poster: poster})
			at = len(seasons) - 1
			index[seasonID] = at
		}
		seasons[at].Episodes = append(seasons[at].Episodes, episode)
	}
	if seasons == nil {
		seasons = []SeasonRow{}
	}
	return seasons, rows.Err()
}

