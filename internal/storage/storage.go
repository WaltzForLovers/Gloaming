func (db *DB) upsertTitle(ctx context.Context, title Title, synthesize bool) (Title, error) {
	if title.Source == "" {
		title.Source = "tvmaze"
	}
	var owner sql.NullInt64
	err := db.sql.QueryRowContext(ctx, `
INSERT INTO titles (external_id, source, name, year, episode_count, average_minutes, poster, fetched_at, owner_id, genres, summary)
VALUES ($1, $2, $3, $4, $5, $6, $7, $8, NULLIF($9, 0), $10, $11)
ON CONFLICT (source, external_id) DO UPDATE SET
    name = EXCLUDED.name,
    year = EXCLUDED.year,
    episode_count = CASE WHEN EXCLUDED.episode_count > 0 THEN EXCLUDED.episode_count ELSE titles.episode_count END,
    average_minutes = CASE WHEN EXCLUDED.average_minutes > 0 THEN EXCLUDED.average_minutes ELSE titles.average_minutes END,
    poster = CASE WHEN EXCLUDED.poster <> '' THEN EXCLUDED.poster ELSE titles.poster END,
    genres = CASE WHEN EXCLUDED.genres <> '' THEN EXCLUDED.genres ELSE titles.genres END,
    summary = CASE WHEN EXCLUDED.summary <> '' THEN EXCLUDED.summary ELSE titles.summary END,
    fetched_at = EXCLUDED.fetched_at
RETURNING id, external_id, source, name, year, episode_count, average_minutes, poster, owner_id, summary`,
		title.ExternalID, title.Source, title.Name, title.Year, title.EpisodeCount, title.AverageMinutes, title.Poster, time.Now().UTC(), title.OwnerID, joinGenres(title.Genres), title.Summary,
	).Scan(&title.ID, &title.ExternalID, &title.Source, &title.Name, &title.Year, &title.EpisodeCount, &title.AverageMinutes, &title.Poster, &owner, &title.Summary)
	if owner.Valid {
		title.OwnerID = owner.Int64
	}
	if err != nil {
		return Title{}, err
	}
	if synthesize {
		if err := db.ensureEpisodes(ctx, title); err != nil {
			return Title{}, err
		}
	}
	return title, nil
}

func (db *DB) SaveCatalog(ctx context.Context, title Title, seeds []EpisodeSeed, assembling bool) (Title, error) {
	saved, err := db.upsertTitle(ctx, title, false)
	if err != nil {
		return Title{}, err
	}
	if len(seeds) > 0 {
		if err := db.ReplaceEpisodes(ctx, saved.ID, seeds); err != nil {
			return Title{}, err
		}
		if err := db.setAssembling(ctx, saved.ID, false); err != nil {
			return Title{}, err
		}
		saved.Assembling = false
		return saved, nil
	}
	var seasons int
	if err := db.sql.QueryRowContext(ctx, `SELECT COUNT(*) FROM seasons WHERE title_id = $1`, saved.ID).Scan(&seasons); err != nil {
		return Title{}, err
	}
	if seasons > 0 {
		if err := db.setAssembling(ctx, saved.ID, false); err != nil {
			return Title{}, err
		}
		return db.TitleByID(ctx, saved.ID)
	}
	if err := db.setAssembling(ctx, saved.ID, assembling); err != nil {
		return Title{}, err
	}
	saved.Assembling = assembling
	return saved, nil
}

